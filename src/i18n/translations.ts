export type TranslationSet = (typeof TRANSLATIONS)['en'] | (typeof TRANSLATIONS)['ar'];

export function formatLocalizedTime(ts: number, lang: AppLanguage): string {
  return new Intl.DateTimeFormat(lang === 'ar' ? 'ar-AE' : 'en-US', {
    hour: '2-digit',
    minute: '2-digit',
  }).format(new Date(ts));
}

export function formatLocalizedDate(ts: number, lang: AppLanguage): string {
  return new Intl.DateTimeFormat(lang === 'ar' ? 'ar-AE' : 'en-US', {
    month: 'short',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  }).format(new Date(ts));
}

export function formatLocalizedNumber(value: number, lang: AppLanguage): string {
  return new Intl.NumberFormat(lang === 'ar' ? 'ar-AE' : 'en-US').format(value);
}

export function formatBytes(bytes: number, lang: AppLanguage): string {
  if (bytes < 1024) return `${formatLocalizedNumber(bytes, lang)} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(2)} MB`;
}
